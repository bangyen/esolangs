"""Diff a generator's programs against another revision, byte for byte.

The generator refactor check: every table through n=3, also wrapped at width
8 (and below n=3 at widths 1, 3 and 20, and balanced), generated by the old
and the new tree and dumped with :func:`esolangs.to_json`, must match
exactly. Declared construction witnesses add their truth tables and layout
options to both trees' requests. Errors match by type and message.
A change of size or shape
is an optimization, judged by CONTRIBUTING.md's size bar, not a refactor.
Each tree runs in its own process from its own ``src``, so a package
generator and the shared wrapping layers come from the same revision.
``--mutant`` is the positive control; ``--speed`` compares generation time.
The complete sweep has a 300-second wall-clock limit. A sweep timeout exits 124.

Exits 1 on any difference, if neither tree generated a matching pair of
programs, on a mutant that went unseen, or with ``--speed`` on a new tree
more than 10% slower (CONTRIBUTING.md's bar).
"""

from __future__ import annotations

import argparse
import importlib
import itertools
import json
import os
import shutil
import stat
import subprocess
import sys
import tarfile
import tempfile
import time
from collections.abc import Callable, Iterator
from pathlib import Path
from typing import Any, NamedTuple

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "scripts"))

from verify.process import run_bounded  # noqa: E402

#: The slowdown a refactor may cost before ``--speed`` fails it.
SLOWDOWN = 0.10
_DUMP_TIMEOUT = 60
_SWEEP_TIMEOUT = 300
_MAX_EXHAUSTIVE_ARITY = 3
_WITNESS_ROWS = 1 << 20
type Outputs = dict[str, str]
type WitnessRequests = dict[str, tuple[str, dict[str, Any]]]


class Timings(NamedTuple):
    """Elapsed time for generation and portable serialization."""

    generation: float
    serialization: float


def _exhaustive_options(n: int) -> list[dict[str, Any]]:
    if n < 3:
        return [{}, *({"width": w} for w in (1, 3, 8, 20)), {"balance": True}]
    return [{}, {"width": 8}]


def _exhaustive_count(max_n: int) -> int:
    """Price the sweep before creating tables, bounding even the estimate."""
    if max_n < 0:
        raise ValueError("--max-n must be nonnegative")
    through = min(max_n, _MAX_EXHAUSTIVE_ARITY + 2)
    count = sum(
        (1 << (1 << n)) * len(_exhaustive_options(n)) for n in range(1, through + 1)
    )
    if max_n > _MAX_EXHAUSTIVE_ARITY:
        bound = "at least " if through < max_n else ""
        raise ValueError(
            f"--max-n {max_n} requires {bound}{count:,} exhaustive requests per pass; "
            f"the budget allows arities through {_MAX_EXHAUSTIVE_ARITY}. "
            "Use named construction witnesses for larger arities."
        )
    return count


def _requests(
    max_n: int, witnesses: WitnessRequests
) -> Iterator[tuple[str, str, dict[str, Any]]]:
    _exhaustive_count(max_n)
    for n in range(1, max_n + 1):
        options = _exhaustive_options(n)
        for table in map("".join, itertools.product("01", repeat=1 << n)):
            for option in options:
                yield f"{table} {json.dumps(option)}", table, option
    for label, (table, option) in witnesses.items():
        yield label, table, option


def outputs(
    name: str, max_n: int = 3, *, witnesses: WitnessRequests | None = None
) -> Outputs:
    """Return each dumped program or error from the tree under test."""
    return _timed_outputs(name, max_n, witnesses or {})[0]


def _timed_outputs(
    name: str, max_n: int, witnesses: WitnessRequests
) -> tuple[Outputs, Timings]:
    import esolangs

    found: Outputs = {}
    generation = serialization = 0.0
    for key, table, option in _requests(max_n, witnesses):
        try:
            started = time.perf_counter()
            try:
                program = esolangs.generate(name, table, **option)
            finally:
                generation += time.perf_counter() - started
            started = time.perf_counter()
            try:
                found[key] = esolangs.to_json(name, program)
            finally:
                serialization += time.perf_counter() - started
        except Exception as error:
            found[key] = f"{type(error).__name__}: {error}"
    return found, Timings(generation, serialization)


def _construction_tables(name: str, max_n: int) -> WitnessRequests:
    """Materialize witnesses outside the exhaustive requests once for all laps."""
    from docs.evidence import construction_records

    try:
        boundaries = construction_records(name)
    except FileNotFoundError:
        return {}
    cases: WitnessRequests = {}
    requests = set()
    seen = set()
    rows = 0
    for label, boundary in boundaries.items():
        options = boundary.generation_options()
        for witness in boundary.witnesses:
            if witness.arity <= max_n and options in _exhaustive_options(witness.arity):
                continue
            spec = witness, boundary.width, boundary.balance
            if spec in seen:
                continue
            seen.add(spec)
            if witness.arity > _WITNESS_ROWS.bit_length() - 1:
                raise SystemExit(f"{name}: witness {label} exceeds the row budget")
            rows += 1 << witness.arity
            if rows > _WITNESS_ROWS:
                raise SystemExit(
                    f"{name}: construction witnesses exceed the row budget"
                )
            table = witness.table()
            request = table, tuple(options.items())
            if request not in requests:
                requests.add(request)
                cases[f"{label} n={witness.arity} {witness.name}"] = table, options
    return cases


def _dump(
    src: Path, name: str, max_n: int, witnesses: WitnessRequests
) -> tuple[Outputs, Timings]:
    """Run :func:`outputs` against the tree at ``src``; return it and its time."""
    env = dict(os.environ, PYTHONPATH=str(src))
    command = [sys.executable, __file__, "--dump", name, "--max-n", str(max_n)]
    try:
        result = run_bounded(
            command,
            env=env,
            stdin_text=json.dumps(witnesses),
            capture_output=True,
            timeout=_DUMP_TIMEOUT,
        )
    except subprocess.TimeoutExpired:
        raise SystemExit(
            f"generating {name} from {src} exceeded {_DUMP_TIMEOUT}s"
        ) from None
    if result.returncode:
        raise SystemExit(f"generating from {src} failed:\n{result.stderr[-2000:]}")
    dumped = json.loads(result.stdout)
    return dumped["outputs"], Timings(*dumped["seconds"])


def _checkout(ref: str, scratch: Path) -> Path:
    """Write ``src`` as it is at git ``ref`` into ``scratch``; return it."""
    try:
        commit = subprocess.run(
            ["git", "rev-parse", "--verify", "--end-of-options", f"{ref}^{{commit}}"],
            cwd=ROOT,
            check=True,
            capture_output=True,
            text=True,
            timeout=10,
        ).stdout.strip()
    except (OSError, subprocess.CalledProcessError, subprocess.TimeoutExpired) as error:
        raise ValueError(
            f"--old {ref!r} does not resolve to a readable commit"
        ) from error
    scratch.mkdir(parents=True)
    archive = scratch / "src.tar"
    try:
        with archive.open("wb") as out:
            subprocess.run(
                ["git", "archive", commit, "--", "src"],
                cwd=ROOT,
                check=True,
                stdout=out,
                stderr=subprocess.PIPE,
                timeout=_DUMP_TIMEOUT,
            )
    except (OSError, subprocess.CalledProcessError, subprocess.TimeoutExpired) as error:
        raise ValueError(f"could not read src from --old {ref!r}: {error}") from error
    with tarfile.open(archive) as tar:
        tar.extractall(scratch, filter="data")
    return scratch / "src"


def _mutant_target(name: str, target: Path | None) -> Path:
    """Locate the generator entry point or an explicitly selected package file."""
    import esolangs.registry

    backend = esolangs.registry.LANGUAGES[name].backend
    if backend is None:
        raise ValueError(f"{name} has no Boolean generator")
    module = backend.generate.__module__
    entry = Path(importlib.import_module(module).__file__ or "")
    return _replacement_target(entry, target, "generator")


def _replacement_target(entry: Path, target: Path | None, kind: str) -> Path:
    """Limit replacements to the entry point or a file in its package."""
    entry = entry.resolve()
    path = entry if target is None else (ROOT / target).resolve()
    if path != entry and (
        entry.name != "__init__.py" or not path.is_relative_to(entry.parent)
    ):
        raise ValueError(
            f"mutant target must be the {kind} or one of its package files"
        )
    if (
        not path.is_relative_to(ROOT / "src")
        or not path.is_file()
        or path.suffix != ".py"
    ):
        raise ValueError(
            "mutant target must be an existing Python source file under src"
        )
    return path


def _read_mutant(path: Path) -> bytes:
    """Snapshot a replacement file before spending time on either baseline."""
    try:
        if not stat.S_ISREG(path.stat().st_mode):
            raise ValueError(f"--mutant {str(path)!r} must be a regular file")
        return path.read_bytes()
    except OSError as error:
        raise ValueError(
            f"cannot read --mutant {str(path)!r}: {error.strerror}"
        ) from error


def _mutated(mutant: bytes, target: Path, scratch: Path) -> Path:
    """Copy the working source tree and replace only the selected file."""
    src = scratch / "src"
    shutil.copytree(ROOT / "src", src, ignore=shutil.ignore_patterns("__pycache__"))
    (src / target.relative_to(ROOT / "src")).write_bytes(mutant)
    return src


def differences(old: Outputs, new: Outputs) -> list[str]:
    """Return the requests whose program or error differs."""
    return [key for key in old.keys() | new.keys() if old.get(key) != new.get(key)]


def _speed_failed(
    dump: Callable[[Path], tuple[Outputs, Timings]],
    expected: Outputs,
    old: tuple[str, Path, Timings],
    new: tuple[str, Path, Timings],
) -> bool:
    """Compare best-of-three timings only for stable, identical outputs."""
    old_laps, new_laps = [old[2]], [new[2]]
    for lap in (2, 3):
        for (label, source, _), timings in ((old, old_laps), (new, new_laps)):
            outputs, timing = dump(source)
            changed = differences(expected, outputs)
            if changed:
                print(
                    f"{label}: generation changed on timing pass {lap}: {min(changed)}",
                    file=sys.stderr,
                )
                return True
            timings.append(timing)
    old_generation = min(lap.generation for lap in old_laps)
    new_generation = min(lap.generation for lap in new_laps)
    if min(old_generation, new_generation) <= 0:
        print("generation timings must be positive", file=sys.stderr)
        return True
    change = new_generation / old_generation - 1
    print(
        f"speed: generation {old_generation:.3f}s -> {new_generation:.3f}s "
        f"({change:+.0%})"
    )
    print(
        f"serialization: {min(lap.serialization for lap in old_laps):.3f}s -> "
        f"{min(lap.serialization for lap in new_laps):.3f}s"
    )
    return new_generation > old_generation * (1 + SLOWDOWN)


def main(
    argv: list[str] | None = None,
    *,
    supervise: bool = False,
    scratch: Path | None = None,
) -> int:
    """Print the first differences and the counts; return the exit status."""
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("language")
    parser.add_argument("--old", default="main", help="git revision (default main)")
    parser.add_argument("--mutant", type=Path, help="broken generator module copy")
    parser.add_argument(
        "--mutant-target", type=Path, help="repo-relative generator file to replace"
    )
    parser.add_argument(
        "--max-n",
        type=int,
        default=_MAX_EXHAUSTIVE_ARITY,
        help=f"highest exhaustive arity (0-{_MAX_EXHAUSTIVE_ARITY}); "
        "larger arities use named witnesses",
    )
    parser.add_argument("--speed", action="store_true", help="also compare time")
    parser.add_argument("--dump", action="store_true", help=argparse.SUPPRESS)
    argv = sys.argv[1:] if argv is None else argv
    args = parser.parse_args(argv)
    if args.mutant_target is not None and args.mutant is None:
        parser.error("--mutant-target requires --mutant")
    try:
        exhaustive = _exhaustive_count(args.max_n)
    except ValueError as error:
        parser.error(str(error))
    if args.dump:
        witnesses = json.load(sys.stdin)
        dumped, seconds = _timed_outputs(args.language, args.max_n, witnesses)
        print(json.dumps({"outputs": dumped, "seconds": seconds}))
        return 0
    if supervise:
        return _supervise(argv, args.language)
    sys.path.insert(0, str(ROOT / "src"))
    from esolangs.registry import LANGUAGES, resolve

    try:
        name = resolve(args.language)
        if not LANGUAGES[name].has_backend:
            raise ValueError(f"{name} has no Boolean generator")
        witnesses = _construction_tables(name, args.max_n) if not exhaustive else None
        if witnesses is not None and not witnesses:
            raise ValueError(
                f"{name}: no generation requests; use --max-n 1 "
                "or add construction witnesses"
            )
        replacement = (
            (_mutant_target(name, args.mutant_target), _read_mutant(args.mutant))
            if args.mutant is not None
            else None
        )
    except ValueError as exc:
        parser.error(str(exc))
    with tempfile.TemporaryDirectory(dir=scratch) as directory:
        staging = Path(directory)
        try:
            old_src = _checkout(args.old, staging / "old")
        except ValueError as error:
            parser.error(str(error))
        if witnesses is None:
            witnesses = _construction_tables(name, args.max_n)
        requests = exhaustive + len(witnesses)
        passes = (6 if args.speed else 2) + (args.mutant is not None)
        print(
            f"{name}: {requests:,} generation requests per pass, "
            f"up to {requests * passes:,} across {passes} passes",
            flush=True,
        )

        def dump(source: Path) -> tuple[Outputs, Timings]:
            return _dump(source, name, args.max_n, witnesses)

        new_src = ROOT / "src"
        old, old_time = dump(old_src)
        new, new_time = dump(new_src)
        found = sorted(differences(old, new))
        for key in found[:3]:
            print(f"DIFF {key}")
            print(f"  {args.old}: {old.get(key)!r:.300}")
            print(f"  new: {new.get(key)!r:.300}")
        errors = sum(not text.startswith("{") for text in new.values())
        print(
            f"{name}: {len(new)} programs ({errors} errors), "
            f"{len(found)} differ from {args.old}"
        )
        if witnesses:
            print(f"additional construction witnesses: {len(witnesses)}")
        if not any(
            text.startswith("{") and old.get(key) == text for key, text in new.items()
        ):
            print(f"{name}: no matching successful generation pairs", file=sys.stderr)
            return 1
        failed = bool(found)
        if args.speed and not failed:
            failed = _speed_failed(
                dump, old, (args.old, old_src, old_time), ("new", new_src, new_time)
            )
        if replacement is not None:
            target, contents = replacement
            mutant_src = _mutated(contents, target, staging / "mutant")
            caught = len(differences(new, dump(mutant_src)[0]))
            print(f"control: mutant differs on {caught}")
            failed |= not caught
    return int(failed)


def _supervise(argv: list[str], name: str) -> int:
    """Bound the sweep and own its scratch directory through a worker timeout."""
    with tempfile.TemporaryDirectory(prefix="gendiff-") as directory:
        command = [sys.executable, "-u", __file__, "--sweep", directory, *argv]
        try:
            return run_bounded(command, timeout=_SWEEP_TIMEOUT).returncode
        except subprocess.TimeoutExpired:
            print(
                f"generation sweep for {name} exceeded {_SWEEP_TIMEOUT:g}s",
                file=sys.stderr,
            )
            return 124


if __name__ == "__main__":
    if sys.argv[1:2] == ["--sweep"] and len(sys.argv) > 2:
        raise SystemExit(main(sys.argv[3:], scratch=Path(sys.argv[2])))
    raise SystemExit(main(supervise=True))
