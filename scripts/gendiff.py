"""Diff a generator's programs against another revision, byte for byte.

The generator refactor check: every table through n=3, also wrapped at width
8 (and below n=3 at widths 1, 3 and 20, and balanced), generated by the old
and the new tree and dumped with :func:`esolangs.dump_program`, must match
exactly; an error must match by type and message.  A change of size or shape
is an optimization, judged by CONTRIBUTING.md's size bar, not a refactor.
Each tree runs in its own process from its own ``src``, so a package
generator and the shared wrapping layers come from the same revision.
``--mutant`` is the positive control; ``--speed`` compares generation time.

Exits 1 on any difference, on a mutant that went unseen, or with ``--speed``
on a new tree more than 10% slower (CONTRIBUTING.md's bar).
"""

from __future__ import annotations

import argparse
import importlib
import itertools
import json
import os
import shutil
import subprocess
import sys
import tarfile
import tempfile
import time
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
#: The slowdown a refactor may cost before ``--speed`` fails it.
SLOWDOWN = 0.10
type Outputs = dict[str, str]


def outputs(name: str, max_n: int = 3) -> Outputs:
    """Return each generation request's dumped program, or its error.

    Imports whichever ``esolangs`` is first on the path: the tree under test.
    """
    import esolangs

    found: Outputs = {}
    for n in range(1, max_n + 1):
        options: list[dict[str, Any]] = (
            [{}, *({"width": w} for w in (1, 3, 8, 20)), {"balance": True}]
            if n < 3
            else [{}, {"width": 8}]
        )
        for table in map("".join, itertools.product("01", repeat=1 << n)):
            for option in options:
                key = f"{table} {json.dumps(option)}"
                try:
                    program = esolangs.generate(name, table, **option)
                    found[key] = esolangs.dump_program(name, program)
                except Exception as error:
                    found[key] = f"{type(error).__name__}: {error}"
    return found


def _dump(src: Path, name: str, max_n: int) -> tuple[Outputs, float]:
    """Run :func:`outputs` against the tree at ``src``; return it and its time."""
    env = dict(os.environ, PYTHONPATH=str(src))
    command = [sys.executable, __file__, "--dump", name, "--max-n", str(max_n)]
    result = subprocess.run(command, env=env, capture_output=True, text=True)
    if result.returncode:
        raise SystemExit(f"generating from {src} failed:\n{result.stderr[-2000:]}")
    dumped = json.loads(result.stdout)
    return dumped["outputs"], dumped["seconds"]


def _checkout(ref: str, scratch: Path) -> Path:
    """Write ``src`` as it is at git ``ref`` into ``scratch``; return it."""
    scratch.mkdir(parents=True)
    archive = scratch / "src.tar"
    with archive.open("wb") as out:
        subprocess.run(["git", "archive", ref, "src"], cwd=ROOT, check=True, stdout=out)
    with tarfile.open(archive) as tar:
        tar.extractall(scratch, filter="data")
    return scratch / "src"


def _mutated(mutant: Path, name: str, scratch: Path) -> Path:
    """Copy the working ``src`` with the generator's module replaced by ``mutant``."""
    import esolangs.registry

    module = esolangs.registry.LANGUAGES[name].boolean.__module__
    target = Path(importlib.import_module(module).__file__ or "")
    src = scratch / "src"
    shutil.copytree(ROOT / "src", src, ignore=shutil.ignore_patterns("__pycache__"))
    shutil.copyfile(mutant, src / target.relative_to(ROOT / "src"))
    return src


def differences(old: Outputs, new: Outputs) -> list[str]:
    """Return the requests whose program or error differs, in order."""
    return [key for key in old.keys() | new.keys() if old.get(key) != new.get(key)]


def main(argv: list[str] | None = None) -> int:
    """Print the first differences and the counts; return the exit status."""
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("language")
    parser.add_argument("--old", default="main", help="git revision (default main)")
    parser.add_argument("--mutant", type=Path, help="broken generator module copy")
    parser.add_argument("--max-n", type=int, default=3)
    parser.add_argument("--speed", action="store_true", help="also compare time")
    parser.add_argument("--dump", action="store_true", help=argparse.SUPPRESS)
    args = parser.parse_args(argv)
    if args.dump:
        start = time.perf_counter()
        dumped = outputs(args.language, args.max_n)
        seconds = time.perf_counter() - start
        print(json.dumps({"outputs": dumped, "seconds": seconds}))
        return 0
    sys.path.insert(0, str(ROOT / "src"))
    from esolangs.registry import resolve

    try:
        name = resolve(args.language)
    except ValueError as exc:
        parser.error(str(exc))
    with tempfile.TemporaryDirectory() as scratch:
        old_src = _checkout(args.old, Path(scratch) / "old")
        old, old_time = _dump(old_src, name, args.max_n)
        new, new_time = _dump(ROOT / "src", name, args.max_n)
        found = sorted(differences(old, new))
        for key in found[:3]:
            print(f"DIFF {key}")
            print(f"  {args.old}: {old.get(key)!r:.300}")
            print(f"  new: {new.get(key)!r:.300}")
        # All-error output matches trivially, as a corpus that never halts did.
        errors = sum(not text.startswith("{") for text in new.values())
        print(
            f"{name}: {len(new)} programs ({errors} errors), "
            f"{len(found)} differ from {args.old}"
        )
        failed = bool(found)
        if args.speed:
            # Best of three each, alternating, as one lap is mostly noise.
            for _ in range(2):
                old_time = min(old_time, _dump(old_src, name, args.max_n)[1])
                new_time = min(new_time, _dump(ROOT / "src", name, args.max_n)[1])
            change = old_time / new_time - 1
            print(f"speed: {old_time:.2f}s -> {new_time:.2f}s ({change:+.0%})")
            failed |= change < -SLOWDOWN
        if args.mutant is not None:
            mutant_src = _mutated(args.mutant, name, Path(scratch) / "mutant")
            caught = len(differences(old, _dump(mutant_src, name, args.max_n)[0]))
            print(f"control: mutant differs on {caught}")
            failed |= not caught
    return int(failed)


if __name__ == "__main__":
    raise SystemExit(main())
