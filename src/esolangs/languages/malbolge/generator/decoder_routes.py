    code.jump(112, 0)
    code.jump(0, 34)
    code.crazy(34)
    for target in (35, 36):
        code.crazy(target)
        code.jump(38, 35)
        code.crazy(target)
    code.short(37)
    code.jump(45, 112)
    code.jump(112, 0)
