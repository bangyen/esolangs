def _column_readout(source: bytearray) -> None:
    start, pointer, end = 44469, 161, 45104
    code = _SpillCode(pointer)
    readout = 209
    code.crazy(170)
    code.jump(171, 74)
    code.jump(74, _ONE_HUB)
    code.jump(_ONE_HUB + 1, 36)
    code.rotate(36)
    for _ in range(4):
        code.jump(38, 35)
        code.rotate(36)
    code.short(37)
    code.jump(45, 112)
    code.crazy(118)
    code.jump(119, 37)
    code.reset()
    code.crazy(154)
    code.rotate(157)
    code.jump(159, 47)
    code.jump(47, _ONE_HUB)
    code.jump(_ONE_HUB + 1, 36)
    code.rotate(36)
    code.reset()
    code.crazy(155)

    def from_lookup() -> None:
        code.jump(156, 98)
        code.jump(98, 82)
        code.long(82)
        code.reset()

    from_lookup()
    code.crazy(153)
    from_lookup()
    code.mix(129, 147)
    code.crazy(231)
    code.jump(236, 126)
    code.crazy(141)
    code.crazy(146)
    code.mix(165, 182)

    def rotate_readout() -> None:
        code.rotate(readout)
        code.jump(210, 102)
        code.long(102)
        code.reset()

    rotate_readout()
    code.crazy(164)
    rotate_readout()
    code.rotate(131)
    code.mix(164, 182)
    rotate_readout()
    code.rotate(131)
    code.jump_code(readout)
    code.write(source, start, end)


