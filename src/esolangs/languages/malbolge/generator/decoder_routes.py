def _column_readout(source: bytearray) -> None:
    start, pointer, end = 44469, 161, 45104
    code = _SpillCode(pointer)
    readout = 209
    code.apply("p", 170)
    code.jump(171, 74)
    code.jump(74, 41551)
    code.jump(41552, 36)
    code.apply("*", 36)
    for _ in range(4):
        code.jump(38, 35)
        code.apply("*", 36)
    code.short(37)
    code.jump(45, 112)
    code.apply("p", 118)
    code.jump(119, 37)
    code.reset()
    code.apply("p", 154)
    code.apply("*", 157)
    code.jump(159, 47)
    code.jump(47, 41551)
    code.jump(41552, 36)
    code.apply("*", 36)
    code.reset()
    code.apply("p", 155)

    def from_lookup() -> None:
        code.jump(156, 98)
        code.jump(98, 82)
        code.long(82)
        code.reset()

    from_lookup()
    code.apply("p", 153)
    from_lookup()
    code.mix(129, 147)
    code.apply("p", 231)
    code.jump(236, 126)
    code.apply("p", 141)
    code.apply("p", 146)
    code.mix(165, 182)

    def rotate_readout() -> None:
        code.apply("*", readout)
        code.jump(210, 102)
        code.long(102)
        code.reset()

    rotate_readout()
    code.apply("p", 164)
    rotate_readout()
    code.apply("*", 131)
    code.mix(164, 182)
    rotate_readout()
    code.apply("*", 131)
    code.apply("i", readout)
    code.write(source, start, end)


