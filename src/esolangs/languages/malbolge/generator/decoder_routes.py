def _skip_spill(source: bytearray) -> None:
    start, pointer, end = 5048, 198, 5199
    code = _SpillCode(pointer)
    code.jump(198, 1)
    code.jump(1, 86)
    code.crazy(88)
    code.jump(90, _SHORT_HUB)
    code.crazy(_SHORT_HUB)

    def return_to_twos() -> None:
        code.jump(_SHORT_HUB + 1, 45)
        code.jump(45, 112)

    def rotate_twos() -> None:
        return_to_twos()
        code.rotate(112)

    rotate_twos()
    code.jump(113, 88)
    code.jump(90, _SHORT_HUB)
    rotate_twos()
    code.jump(113, 88)
    code.rotate(88)
    code.jump(90, _SHORT_HUB)
    rotate_twos()
    code.jump(113, 88)
    code.rotate(88)

    for second in (False, True):
        code.jump(90, _SHORT_HUB)
        code.rotate(_SHORT_HUB)
        rotate_twos()
        if second:
            code.jump(113, 88)
            code.jump(90, _SHORT_HUB)
            rotate_twos()
        code.jump(113, 88)
        code.crazy(88)
    for first in (True, False):
        code.rotate(89)
        code.jump(90, _SHORT_HUB)
        return_to_twos()
        code.crazy(112)
        if first:
            code.jump(113, 88)
            code.crazy(88)
    code.long(116)
    code.reset()
    code.jump(134, 157)
    code.rotate(167)
    code.jump(169, 49)
    code.long(49)
    code.crazy(40)
    code.jump(45, 112)
    code.rotate(112)
    code.long(116)
    code.crazy(40)
    code.jump(51, 187)
    code.crazy(187)
    code.jump(189, 86)
    code.jump(87, _ONE_HUB)
    code.crazy(_ONE_HUB)
    code.jump(_ONE_HUB + 1, 36)
    code.reset()
    code.jump(134, 157)
    code.jump_code(157)
    code.write(source, start, end)


def _write_decoder_routes(source: bytearray) -> None:
    """Join the spill paths, select the column payload, and route the fallthrough."""
    _join_spill_axes(source)
    _column_readout(source)
    _select_payload(source)
    _middle_bridge(source)
    _middle_rejoin(source)
    _skip_spill(source)
