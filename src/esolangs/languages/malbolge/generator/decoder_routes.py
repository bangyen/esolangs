def _join_spill_axes(source: bytearray) -> None:
    start, pointer, end = 18225, 168, 18954
    code = _SpillCode(pointer)
    code.jump(168, 48)
    code.jump(52, 127)
    code.mix(128, 150)
    code.jump(151, 43)
    code.jump(52, 127)
    code.apply("p", 150)
    for word in (151, 152):
        code.apply("p", word)
        code.jump(153, 118)
        code.jump(119, 37)
        code.reset()
        code.apply("p", word)
    code.apply("p", 153)
    for word in (153, 154, 155):
        code.jump(159, 47)
        code.jump(52, 127)
        code.apply("p", word)
        if word < 155:
            code.apply("p", word + 1)

    def to_column() -> None:
        code.jump(162, 58)
        code.jump(59, 118)
        code.jump(119, 37)
        code.jump(38, 35)

    to_column()
    code.apply("p", 36)
    code.jump(38, 35)
    code.apply("p", 36)
    code.reset()
    code.mix(128, 150)
    code.apply("*", 157)
    code.jump(159, 47)
    code.jump(52, 127)
    code.mix(128, 151)
    code.apply("*", 180)
    code.apply("*", 209)
    code.jump(231, 79)
    code.apply("*", 148)
    code.jump(150, 1)
    code.jump(8, 52)
    code.jump(52, 127)
    code.apply("p", 152)
    to_column()
    code.apply("p", 36)
    for _ in range(3):
        code.jump(38, 35)
        code.apply("*", 36)
    code.reset()
    code.apply("*", 160)
    code.jump(166, 125)
    code.mix(160, 165)
    code.jump(166, 125)
    code.mix(128, 160)
    code.jump(166, 125)
    code.apply("p", 157)
    code.apply("i", 160)
    code.write(source, start, end)


def _select_payload(source: bytearray) -> None:
    start, pointer, end = 37909, 210, 38635
    code = _SpillCode(pointer)
    code.jump(210, 102)
    code.long(102)
    code.reset()
    code.mix(129, 142)
    code.jump(144, 69)
    code.jump(72, 125)
    code.apply("*", 142)
    code.apply("*", 150)
    code.jump(151, 1)
    code.jump(4, 82)
    code.long(82)
    code.reset()
    code.apply("p", 142)
    code.jump(144, 69)
    code.jump(72, 125)
    code.mix(129, 142)

    def write_column_and_tap() -> None:
        code.jump(145, 121)
        code.jump(121, 41551)
        code.jump(41552, 36)
        code.apply("p", 36)
        code.short(37)
        code.jump(45, 112)
        code.apply("*", 112)
        write_tap()

    def write_tap() -> None:
        code.jump(113, 88)
        code.jump(89, 54673)
        code.jump(54678, 70)
        code.apply("p", 71)

    def reverse_tap() -> None:
        code.jump(72, 125)
        code.jump(125, 104)
        code.return_to_all_twos()
        code.apply("*", 112)
        write_tap()
        code.jump(73, 41551)
        code.jump(41552, 36)
        code.apply("p", 36)

    write_column_and_tap()
    code.jump(72, 125)
    code.apply("p", 131)
    code.apply("p", 134)
    code.apply("*", 150)
    code.jump(151, 1)
    code.jump(4, 82)
    code.jump(83, 68)
    code.apply("p", 71)
    reverse_tap()
    code.reset()
    code.mix(128, 142)
    write_column_and_tap()
    reverse_tap()

    # The lookup and marker addresses vary. Only their local two-cell
    # spacing enters the emitted instructions.
    lookup, marker = 42361, 51097
    code.jump(38, 35)
    code.jump(36, lookup)
    code.apply("*", lookup)
    code.jump(lookup + 1, 37)
    code.jump(37, 45925)
    code.jump(45927, 121)
    code.long(123)
    code.jump(39, 72)
    code.long(76)
    code.reset()
    code.apply("p", 128)
    code.apply("*", 131)
    code.mix(150, 151)
    code.apply("p", 182)
    code.apply("*", 185)
    code.jump(188, 34)
    code.apply("p", 35)
    code.reset()
    code.apply("p", 154)

    def save_word() -> None:
        code.apply("p", 160)
        code.jump(166, 125)
        code.apply("p", 154)

    code.apply("*", 158)
    save_word()
    code.jump(156, 98)
    code.mix(101, 105)
    code.return_to_all_twos()
    code.jump(112, 0)
    code.jump(0, 34)
    code.apply("p", 35)
    code.reset()
    code.apply("p", 154)
    code.mix(156, 158)
    save_word()
    code.apply("*", 158)
    code.jump(159, 47)
    code.jump(52, 127)
    code.apply("*", 128)
    code.apply("*", 131)
    code.jump(154, marker)
    code.apply("*", marker)
    code.jump(marker + 1, 43)
    code.jump(43, 45925)
    code.jump(45927, 121)
    code.apply("p", 140)
    code.apply("*", 142)
    code.apply("*", 151)
    code.jump(161, 110)
    code.jump(112, 0)
    code.jump(0, 34)
    code.apply("p", 34)
    code.short(37)
    code.jump(45, 112)
