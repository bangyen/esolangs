def _skip_spill(source: bytearray) -> None:
    start, pointer, end = 5048, 198, 5199
    code = _SpillCode(pointer)
    code.jump(198, 1)
    code.jump(1, 86)
    code.apply("p", 88)
    code.jump(90, 45925)
    code.apply("p", 45925)

    def return_to_twos() -> None:
        code.jump(45926, 45)
        code.jump(45, 112)

    def rotate_twos() -> None:
        return_to_twos()
        code.apply("*", 112)

    rotate_twos()
    code.jump(113, 88)
    code.jump(90, 45925)
    rotate_twos()
    code.jump(113, 88)
    code.apply("*", 88)
    code.jump(90, 45925)
    rotate_twos()
    code.jump(113, 88)
    code.apply("*", 88)

    for second in (False, True):
        code.jump(90, 45925)
        code.apply("*", 45925)
        rotate_twos()
        if second:
            code.jump(113, 88)
            code.jump(90, 45925)
            rotate_twos()
        code.jump(113, 88)
        code.apply("p", 88)
    for first in (True, False):
        code.apply("*", 89)
        code.jump(90, 45925)
        return_to_twos()
        code.apply("p", 112)
        if first:
            code.jump(113, 88)
            code.apply("p", 88)
    code.long(116)
    code.reset()
    code.jump(134, 157)
    code.apply("*", 167)
    code.jump(169, 49)
    code.long(49)
    code.apply("p", 40)
    code.jump(45, 112)
    code.apply("*", 112)
    code.long(116)
    code.apply("p", 40)
    code.jump(51, 187)
    code.apply("p", 187)
    code.jump(189, 86)
    code.jump(87, 41551)
    code.apply("p", 41551)
    code.jump(41552, 36)
    code.reset()
    code.jump(134, 157)
    code.apply("i", 157)
    code.write(source, start, end)


def _write_decoder_routes(source: bytearray) -> None:
    """Join the spill paths, select the column payload, and route the fallthrough."""
    _join_spill_axes(source)
    _column_readout(source)
    _select_payload(source)
    _middle_bridge(source)
    _middle_rejoin(source)
    _skip_spill(source)
