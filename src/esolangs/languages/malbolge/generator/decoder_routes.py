def _join_spill_axes(source: bytearray) -> None:
    start, pointer, end = 18225, 168, 18954
    code = _SpillCode(pointer)
    code.jump(168, 48)
    code.jump(52, 127)
    code.mix(128, 150)
    code.jump(151, 43)
    code.jump(52, 127)
    code.crazy(150)
    for word in (151, 152):
        code.crazy(word)
        code.jump(153, 118)
        code.jump(119, 37)
        code.reset()
        code.crazy(word)
    code.crazy(153)
    for word in (153, 154, 155):
        code.jump(159, 47)
        code.jump(52, 127)
        code.crazy(word)
        if word < 155:
            code.crazy(word + 1)

    def to_column() -> None:
        code.jump(162, 58)
        code.jump(59, 118)
        code.jump(119, 37)
        code.jump(38, 35)

    to_column()
    code.crazy(36)
    code.jump(38, 35)
    code.crazy(36)
    code.reset()
    code.mix(128, 150)
    code.rotate(157)
    code.jump(159, 47)
    code.jump(52, 127)
    code.mix(128, 151)
    code.rotate(180)
    code.rotate(209)
    code.jump(231, 79)
    code.rotate(148)
    code.jump(150, 1)
    code.jump(8, 52)
    code.jump(52, 127)
    code.crazy(152)
    to_column()
    code.crazy(36)
    for _ in range(3):
        code.jump(38, 35)
        code.rotate(36)
    code.reset()
    code.rotate(160)
    code.jump(166, 125)
    code.mix(160, 165)
    code.jump(166, 125)
    code.mix(128, 160)
    code.jump(166, 125)
    code.crazy(157)
    code.jump_code(160)
    code.write(source, start, end)


def _select_payload(source: bytearray) -> None:
    start, pointer, end = 37909, 210, 38635
    code = _SpillCode(pointer)
    code.jump(210, 102)
    code.long(102)
    code.reset()
    code.mix(129, 142)
    code.jump(144, 69)
    code.jump(72, 125)
    code.rotate(142)
    code.rotate(150)
    code.jump(151, 1)
    code.jump(4, 82)
    code.long(82)
    code.reset()
    code.crazy(142)
    code.jump(144, 69)
    code.jump(72, 125)
    code.mix(129, 142)

    def write_column_and_tap() -> None:
        code.jump(145, 121)
        code.jump(121, _ONE_HUB)
        code.jump(_ONE_HUB + 1, 36)
        code.crazy(36)
        code.short(37)
        code.jump(45, 112)
        code.rotate(112)
        write_tap()

    def write_tap() -> None:
        code.jump(113, 88)
        code.jump(89, _LONG_HUB)
        code.jump(54678, 70)
        code.crazy(71)

    def reverse_tap() -> None:
        code.jump(72, 125)
        code.jump(125, 104)
        code.return_to_all_twos()
        code.rotate(112)
        write_tap()
        code.jump(73, _ONE_HUB)
        code.jump(_ONE_HUB + 1, 36)
        code.crazy(36)

    write_column_and_tap()
    code.jump(72, 125)
    code.crazy(131)
    code.crazy(134)
    code.rotate(150)
    code.jump(151, 1)
    code.jump(4, 82)
    code.jump(83, 68)
    code.crazy(71)
    reverse_tap()
    code.reset()
    code.mix(128, 142)
    write_column_and_tap()
    reverse_tap()

    # The lookup and marker addresses vary. Only their local two-cell
    # spacing enters the emitted instructions.
    lookup, marker = 42361, 51097
    code.jump(38, 35)
    code.jump(36, lookup)
    code.rotate(lookup)
    code.jump(lookup + 1, 37)
    code.jump(37, _SHORT_HUB)
    code.jump(45927, 121)
    code.long(123)
    code.jump(39, 72)
    code.long(76)
    code.reset()
    code.crazy(128)
    code.rotate(131)
    code.mix(150, 151)
    code.crazy(182)
    code.rotate(185)
    code.jump(188, 34)
    code.crazy(35)
    code.reset()
    code.crazy(154)

    def save_word() -> None:
        code.crazy(160)
        code.jump(166, 125)
        code.crazy(154)

    code.rotate(158)
    save_word()
    code.jump(156, 98)
    code.mix(101, 105)
    code.return_to_all_twos()
    code.jump(112, 0)
    code.jump(0, 34)
    code.crazy(35)
    code.reset()
    code.crazy(154)
    code.mix(156, 158)
    save_word()
    code.rotate(158)
    code.jump(159, 47)
    code.jump(52, 127)
    code.rotate(128)
    code.rotate(131)
    code.jump(154, marker)
    code.rotate(marker)
    code.jump(marker + 1, 43)
    code.jump(43, _SHORT_HUB)
    code.jump(45927, 121)
    code.crazy(140)
    code.rotate(142)
    code.rotate(151)
    code.jump(161, 110)
    code.jump(112, 0)
    code.jump(0, 34)
