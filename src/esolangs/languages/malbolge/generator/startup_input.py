# C and D immediately after the final input instruction.
_INPUT_HANDOFF = (1620, 139)


def _write_first_read(source: bytearray) -> None:
    start, pointer, end = 237, 237, 356
    code = _SpillCode(pointer)
    code.jump(237, 86)
    code.jump(88, 71)
    code.jump(71, 107)
    code.jump(107, 111)
    code.jump(111, 42)
    code.jump(42, 59)
    code.jump(59, 118)
    code.crazy(118)
    code.jump(120, 115)
    code.jump(116, 102)
    code.jump(102, 52)
    code.jump(52, 127)
    code.crazy(140)
    code.jump(142, 126)
    code.crazy(140)
    code.crazy(198)
