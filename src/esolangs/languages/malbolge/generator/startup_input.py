def _first_digit(source: bytearray) -> None:
    start, pointer, end = 356, 92, 1023
    code = _SpillCode(pointer)
    rotation_seed = 43
    code.jump(92, 75)
    code.crazy(75)
    code.jump(81, 55)
    code.jump(57, 43)
    for pass_index in range(2):
        code.rotate(rotation_seed)
        for _ in range(2):
            code.jump(44, 108)
            code.jump(111, 42)
            code.rotate(rotation_seed)
        code.jump(45, 112)
        code.crazy(112)
        if pass_index == 0:
            code.jump(113, 88)
            code.jump(90, 56)
            code.jump(57, 43)
    code.rotate(118)
    code.jump(120, 115)
    code.jump(116, 102)
    code.jump(102, 52)
    code.jump(52, 127)
    code.crazy(128)

    def return_mask(operand: int) -> None:
        code.jump(operand, 65)
        code.return_to_rotation_seed()

    return_mask(130)
    code.crazy(128)
    code.crazy(129)
    return_mask(130)
    code.crazy(129)
    return_mask(130)
    for _ in range(2):
        code.jump(127, 94)
        code.jump(94, 34)
        code.crazy(34)
        return_mask(36)
    code.crazy(130)
    code.jump(133, 72)
    code.jump(72, 125)
    code.crazy(130)
    code.jump(131, 106)
    code.return_to_all_twos()
    code.rotate(112)
    code.jump(114, 124)
    code.crazy(129)
    code.rotate(130)
    code.crazy(202)
    code.jump(203, 46)
    code.jump(48, 126)
    code.crazy(173)
    code.crazy(174)
    code.mix(185, 187)
    code.rotate(197)
    code.mix(198, 202)
    code.crazy(203)

    code.return_to_staged_word()
    code.crazy(203)
    code.return_to_staged_word()
    code.crazy(149)
    code.jump(152, 90)
    code.jump(91, 84)
    code.jump(84, 50)
    code.jump(52, 127)
    code.crazy(149)
    for _ in range(2):
        code.crazy(201)
        code.return_to_staged_word()
    code.crazy(133)
    code.jump(134, 64)
    code.return_to_rotation_seed()
    code.crazy(133)
    code.crazy(147)
    code.jump(148, 40)
    code.jump(40, 64)
    code.return_to_rotation_seed()
    code.crazy(147)
    code.crazy(148)
    code.jump(149, 29525)
    code.jump(29525, 60)
    code.jump(61, 100)
    code.jump(102, 52)
    code.jump(52, 127)
    code.crazy(148)
    code.jump(149, 29525)
    code.jump(29525, 60)
    code.read(60)
    code.write(source, start, end)


def _through_reset_seed(code: _SpillCode) -> None:
    code.jump(48, 126)
    code.jump(127, 94)
    code.jump(94, 34)


