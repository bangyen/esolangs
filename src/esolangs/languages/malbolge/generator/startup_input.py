def _read_suffix(source: bytearray) -> None:
    start, pointer = 1589, 132
    end, next_pointer = _INPUT_HANDOFF
    code = _SpillCode(pointer)
    code.crazy(132)
    code.rotate(133)
    code.jump(134, 64)
    code.return_to_rotation_seed()
    code.crazy(126)
    code.jump(129, 0)
    code.jump(1, 86)
    code.crazy(86)
    code.jump(89, 51)
    code.jump(52, 127)
    code.crazy(127)
    code.mix(129, 132)
    code.read(next_pointer - 1)
    code.write(source, start, end)


def _write_input_routes(source: bytearray) -> None:
    """Fold the seventeen input bits and leave C1620/D139 after the last read."""
    _write_first_read(source)
    _first_digit(source)
    _finish_first_group(source)
    _fold_second_group(source)
    _fold_third_group(source)
    _fold_fourth_group(source)
    _fold_fifth_group(source)
    _read_suffix(source)
