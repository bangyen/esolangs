def _shadow_payload(source: bytearray) -> None:
    slot, palette = 42305, 4262
    start, pointer, end = 6185, 158, 6560
    code = _SpillCode(pointer)
    code.apply("*", 158)
    code.jump(159, 47)
    code.apply("p", 48)
    code.jump(52, 127)

    def payload_transform() -> None:
        # Follow the shared navigation after the payload write.
        # The concrete slot is used only to describe its two-word offset.
        code.apply("*", 129)
        code.jump(153, slot)
        code.apply("p", slot)
        code.jump(slot + 3, 126)
        code.jump(126, 29525)
        code.jump(29525, 93)
        code.jump(93, 113)
        code.jump(113, 88)
        code.jump(88, 29525)
        code.jump(29525, 93)
        code.jump(94, 41551)
        code.jump(41552, 36)
        code.jump(38, 35)
        code.jump(35, 29525)
        code.jump(29525, 93)
        code.jump(93, 113)
        code.jump(114, 41551)
        code.jump(41552, 36)
        code.jump(36, 29525)
        code.jump(29525, 93)
        code.jump(94, 41551)
        code.jump(41553, 35)

    def return_from_palette() -> None:
        code.jump(palette + 1, 49)
        for repeat in range(3):
            code.jump(49, 54673)
            code.jump(54673, 31388)
            if repeat < 2:
                code.jump(31388, 49)
        code.jump(31389, 48)
        code.jump(49, 54673)
        code.jump(54675, 38)
        code.jump(40, 41551)

    code.apply("*", 128)
    payload_transform()
    code.reset()
    code.apply("*", 128)
    payload_transform()
    code.apply("p", 35)
    code.reset()
    code.apply("*", 128)
    code.apply("*", 129)
    code.jump(135, 36)
    code.jump(38, 35)
    code.apply("p", 35)
    code.reset()
    code.apply("p", 131)
    code.jump(135, 36)
    code.reset()
    code.apply("*", 128)
    code.jump(129, 0)
    code.jump(0, 34)
    code.apply("*", 36)
    for _ in range(2):
        code.jump(38, 35)
        code.apply("p", 35)
    code.reset()
    code.jump(131, palette)
    code.apply("p", palette)
    return_from_palette()
    code.jump(41552, 36)
    code.short(37)
    code.jump(47, 41551)
    code.jump(41552, 36)
    code.reset()
    code.jump(131, palette)
    code.apply("p", palette)
    return_from_palette()
    code.jump(41551, 11786)
    code.jump(11786, 85)
    code.jump(86, 29525)
    code.jump(29526, 38)
    code.jump(38, 35)
    code.short(37)
    code.jump(45, 112)
    code.jump(112, 29525)
    code.jump(29525, 93)
    code.short(97)
    code.apply("*", 52)
    code.jump(57, 45925)
    code.jump(45927, 121)
    code.apply("p", 122)
    for _ in range(2):
        code.jump(124, 45925)
        code.jump(45927, 121)
        code.apply("*", 122)
    code.apply("p", 126)
    code.apply("p", 128)
    code.jump(131, palette)
    code.apply("p", palette)
    return_from_palette()
    code.jump(41552, 36)
    code.short(37)
    code.jump(50, 45925)
    code.jump(45927, 121)
    code.apply("*", 122)
    code.apply("*", 126)
    code.jump(131, palette)
    code.apply("i", palette)
    code.write(source, start, end)


def _write_decoder_tail(source: bytearray) -> None:
    """Emit the marker handoff and the low lookup return paths."""
    _marker_handoff(source)
    _lookup_guard(source)
    _lookup_rejoin(source)
    _palette_return(source)
    _shadow_payload(source)
