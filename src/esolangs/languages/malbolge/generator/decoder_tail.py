"""Marker handoff and final lookup paths for the packed decoder."""

from .packed_layout import (
    _LONG_HUB,
    _ONE_HUB,
    _SHORT_HUB,
    _SPILL_MARKER_BASE,
)
from .spill_routes import _SpillCode


def _marker_handoff(source: bytearray) -> None:
    start, pointer, end = 4699, 137, 5047
    code = _SpillCode(pointer)
    code.jump(142, 126)
    code.jump(126, 163)
    code.crazy(173)

    def write_long_hub() -> None:
        code.jump(175, 55)
        code.jump(55, _LONG_HUB)
        code.crazy(_LONG_HUB)

    write_long_hub()
    code.jump(54675, 38)
    code.jump(38, 35)
    code.jump(35, _LONG_HUB)
    code.crazy(_LONG_HUB)
    code.jump(_LONG_HUB + 1, 39)
    code.reset()
    code.jump(126, 163)
    code.crazy(173)
    write_long_hub()
    code.jump(_LONG_HUB + 1, 39)
    code.reset()
    code.jump(128, 29525)
    code.jump(29526, 59)
    code.jump(59, 118)
    code.rotate(118)
    code.jump(120, _ONE_HUB)
    code.crazy(_ONE_HUB)
    code.jump(_ONE_HUB + 1, 36)
    code.jump(36, 65)
    code.jump(65, 47)
    code.jump(47, _ONE_HUB)
    code.crazy(_ONE_HUB)
    code.jump(_ONE_HUB + 1, 36)
    code.jump(37, _SHORT_HUB)
    code.crazy(_SHORT_HUB)
    code.jump(45927, 121)
    code.jump(124, _SHORT_HUB)
    code.crazy(_SHORT_HUB)
    code.jump(_SHORT_HUB + 1, 45)
    code.jump(45, 112)
    code.jump(112, 0)
    code.jump(4, 82)
    code.crazy(82)
    code.rotate(83)
    code.short(84)
    code.jump(48, 126)
    code.jump(126, 163)
    code.jump(163, 99)
    code.rotate(101)
    code.jump(102, _LONG_HUB)
    code.jump(54677, 100)
    code.rotate(101)
    for _ in range(3):
        code.long(102)
        code.reset()
        code.jump(126, 163)
        code.jump(163, 99)
        code.rotate(101)
    code.long(102)
    code.jump(40, _ONE_HUB)
    code.crazy(_ONE_HUB)
    code.jump(_ONE_HUB + 1, 36)
    code.jump(36, 65)
    code.rotate(65)
    for _ in range(4):
        code.jump(67, _ONE_HUB)
        code.jump(_ONE_HUB + 1, 36)
        code.jump(36, 65)
        code.rotate(65)
    code.jump(70, _SHORT_HUB)
    code.crazy(_SHORT_HUB)
    code.jump(_SHORT_HUB + 1, 45)
    code.jump(48, 126)
    code.jump(126, 163)
    code.rotate(182)
    code.jump(183, 51)
    code.jump(51, 121)
    code.jump(121, _ONE_HUB)
    code.jump(_ONE_HUB + 1, 36)
    code.jump(36, 65)
    code.crazy(65)
    code.jump(72, 125)
    code.rotate(126)
    for _ in range(2):
        code.jump(127, _ONE_HUB)
        code.jump(_ONE_HUB, 11786)
        code.jump(11787, 126)
        code.rotate(126)
    code.jump(142, 126)
    code.rotate(126)
    code.mix(157, 180)
    code.rotate(182)
    code.mix(185, 196)
    code.crazy(197)
    code.mix(198, 199)

    # The selected row changes the high marker address, while its
    # return path uses the same relative sequence of operations.
    marker = _SPILL_MARKER_BASE + 22
    code.jump(203, marker)
    code.jump(marker, 107)
    code.jump(107, _ONE_HUB)
    code.jump(_ONE_HUB, 11786)
    code.jump(11786, 99)
    code.jump(99, 44)
    for exit_word, landing in ((24908, 43), (24909, 70)):
        code.jump(44, _SHORT_HUB)
        code.jump(_SHORT_HUB, 24908)
        code.jump(exit_word, landing)
    code.jump(71, 107)
    code.jump(108, 91)
    code.jump(93, 113)
    code.jump(114, _ONE_HUB)
    code.jump_code(_ONE_HUB)
    code.write(source, start, end)


def _save_lookup(code: _SpillCode, lookup: int) -> None:
    code.jump(86, lookup)
    code.crazy(lookup + 8)


def _return_from_lookup(code: _SpillCode, lookup: int) -> None:
    code.jump(lookup + 9, 121)
    code.jump(127, _ONE_HUB)
    code.jump(_ONE_HUB + 1, 36)


def _through_shadow(code: _SpillCode) -> None:
    shadow = 15309
    code.jump(41, 36)
    code.jump(37, shadow)
    code.jump(shadow, 82)
    code.jump(83, 68)


def _lookup_guard(source: bytearray) -> None:
    # The concrete lookup address only establishes a relative eight-cell walk.
    lookup = 5327
    start, pointer, end = 5565, 158, 5627
    code = _SpillCode(pointer)
    code.jump(159, 47)
    code.jump(51, 187)
    code.jump(189, 86)
    _save_lookup(code, lookup)
    _return_from_lookup(code, lookup)
    _through_shadow(code)
    code.short(70)
    code.jump(46, 29525)
    code.jump(29525, 93)
    code.jump(95, 86)
    code.jump(86, lookup)
    code.jump_code(lookup + 8)
    code.write(source, start, end)


