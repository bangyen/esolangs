def _shadow_payload(source: bytearray) -> None:
    slot, palette = 42305, 4262
    start, pointer, end = 6185, 158, 6560
    code = _SpillCode(pointer)
    code.rotate(158)
    code.jump(159, 47)
    code.crazy(48)
    code.jump(52, 127)

    def payload_transform() -> None:
        # Follow the shared navigation after the payload write.
        # The concrete slot is used only to describe its two-word offset.
        code.rotate(129)
        code.jump(153, slot)
        code.crazy(slot)
        code.jump(slot + 3, 126)
        code.jump(126, 29525)
        code.jump(29525, 93)
        code.jump(93, 113)
        code.jump(113, 88)
        code.jump(88, 29525)
        code.jump(29525, 93)
        code.jump(94, _ONE_HUB)
        code.jump(_ONE_HUB + 1, 36)
        code.jump(38, 35)
        code.jump(35, 29525)
        code.jump(29525, 93)
        code.jump(93, 113)
        code.jump(114, _ONE_HUB)
        code.jump(_ONE_HUB + 1, 36)
        code.jump(36, 29525)
        code.jump(29525, 93)
        code.jump(94, _ONE_HUB)
        code.jump(41553, 35)

    def return_from_palette() -> None:
        code.jump(palette + 1, 49)
        for repeat in range(3):
            code.jump(49, _LONG_HUB)
            code.jump(_LONG_HUB, 31388)
            if repeat < 2:
                code.jump(31388, 49)
        code.jump(31389, 48)
        code.jump(49, _LONG_HUB)
        code.jump(54675, 38)
        code.jump(40, _ONE_HUB)

    code.rotate(128)
    payload_transform()
    code.reset()
    code.rotate(128)
    payload_transform()
    code.crazy(35)
    code.reset()
    code.rotate(128)
    code.rotate(129)
    code.jump(135, 36)
    code.jump(38, 35)
    code.crazy(35)
    code.reset()
    code.crazy(131)
    code.jump(135, 36)
    code.reset()
    code.rotate(128)
    code.jump(129, 0)
    code.jump(0, 34)
    code.rotate(36)
    for _ in range(2):
        code.jump(38, 35)
        code.crazy(35)
    code.reset()
    code.jump(131, palette)
    code.crazy(palette)
    return_from_palette()
    code.jump(_ONE_HUB + 1, 36)
    code.short(37)
    code.jump(47, _ONE_HUB)
    code.jump(_ONE_HUB + 1, 36)
    code.reset()
    code.jump(131, palette)
    code.crazy(palette)
    return_from_palette()
    code.jump(_ONE_HUB, 11786)
    code.jump(11786, 85)
    code.jump(86, 29525)
    code.jump(29526, 38)
    code.jump(38, 35)
    code.short(37)
    code.jump(45, 112)
    code.jump(112, 29525)
    code.jump(29525, 93)
    code.short(97)
    code.rotate(52)
    code.jump(57, _SHORT_HUB)
    code.jump(45927, 121)
    code.crazy(122)
    for _ in range(2):
        code.jump(124, _SHORT_HUB)
        code.jump(45927, 121)
        code.rotate(122)
    code.crazy(126)
    code.crazy(128)
    code.jump(131, palette)
    code.crazy(palette)
    return_from_palette()
    code.jump(_ONE_HUB + 1, 36)
    code.short(37)
    code.jump(50, _SHORT_HUB)
    code.jump(45927, 121)
    code.rotate(122)
    code.rotate(126)
    code.jump(131, palette)
    code.jump_code(palette)
    code.write(source, start, end)


def _write_decoder_tail(source: bytearray) -> None:
    """Emit the marker handoff and the low lookup return paths."""
    _marker_handoff(source)
    _lookup_guard(source)
    _lookup_rejoin(source)
    _palette_return(source)
    _shadow_payload(source)
