def _prime_pointer(code: _SpillCode, cell: int, *returns: tuple[int, int]) -> None:
    """Apply the mask twice with the intervening pointer return."""
    code.crazy(cell)
    for operand, landing in returns:
        code.jump(operand, landing)
    code.crazy(cell)


