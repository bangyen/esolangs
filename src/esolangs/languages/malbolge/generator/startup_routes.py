def _write_dispatch_setup(source: bytearray) -> None:
    """Prepare the hub operands and dispatch from the completed input fold."""
    _save_suffix_and_readout(source)
    _seed_address_rotations(source)
    _finish_address_rotations(source)
    _stage_address_residues(source)
    _reload_residue_mask(source)
    _prime_hub_operands(source)
    _prepare_short_hub(source)
    _prepare_one_hub(source)
    _prepare_long_hub(source)
    _enter_dispatch(source)

    # Cold operands shared with the palette and the dispatch entries.
    source[4252] = _char_for("p", 4252)
    source[5047] = _char_for("j", 5047)
    source[5564] = _char_for("j", 5564)
    # Complete the cold printer seed before the layout stamps its active stubs.
    for address, op in enumerate("joo*ppopp<v", 4607):
        source[address] = _char_for(op, address)
    source[4690] = _char_for("*", 4690)
