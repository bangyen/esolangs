"""Run every committed example program and check its output.

The hello-world examples are generated by ``esolangs.tools.text`` and
committed under ``examples/hello-world``.  Each is run through its interpreter
and must reproduce ``Hello, World!``; a companion test keeps the files in sync
with whatever the generators currently produce.  The hand-written cat and
truth-machine examples under ``examples/cat`` and ``examples/truth-machine``
are also run.  A truth machine echoes ``0`` and halts when given ``0``; its
``1`` branch loops forever by design and is not executed.
"""

import importlib
import io
from contextlib import redirect_stdout
from pathlib import Path
from unittest.mock import patch

import pytest

from esolangs.interpreters.io import IO
from esolangs.registry import LANGUAGES

EXAMPLES_DIR = Path(__file__).parent.parent / "examples" / "hello-world"


def _file_name(display_name: str) -> str:
    return display_name.lower().replace(" ", "-")


# example file stem -> (interpreter module, split lines, kwargs), derived
# from the language registry.
EXAMPLES = {
    _file_name(lang.name): (lang.interpreter, lang.split, dict(lang.kwargs))
    for lang in LANGUAGES.values()
    if lang.generator and lang.interpreter
}

# container halts by calling sys.exit(0)
EXITS = {"container"}


def run_example(name: str) -> str:
    module, splitlines, kwargs = EXAMPLES[name]
    run = importlib.import_module("esolangs.interpreters." + module).run
    program = (EXAMPLES_DIR / f"{name}.txt").read_text(encoding="utf-8").rstrip("\n")
    argument = program.splitlines() if splitlines else program

    buffer = io.StringIO()
    try:
        with redirect_stdout(buffer):
            run(argument, io=IO(), **kwargs)
    except SystemExit:
        assert name in EXITS, f"{name} exited unexpectedly"
    return buffer.getvalue()


@pytest.mark.parametrize("name", sorted(EXAMPLES))
def test_hello_world_example(name: str) -> None:
    expected = "Hello, World!\n" if name == "nevermind" else "Hello, World!"
    assert run_example(name) == expected


def test_example_files_match_generator() -> None:
    """The committed examples are exactly what the generators produce today."""
    generators = {
        _file_name(lang.name): lang.generator
        for lang in LANGUAGES.values()
        if lang.generator and lang.interpreter
    }
    for name, generator in generators.items():
        path = EXAMPLES_DIR / f"{name}.txt"
        assert path.read_text(encoding="utf-8") == generator("Hello, World!")


def test_no_orphan_hello_world_examples() -> None:
    """Every hello-world file belongs to a language that still has a generator.

    The other tests derive their parameters from the registry, so a file for a
    language that was removed is never collected and cannot fail.  Scanning the
    directory is what catches it.
    """
    committed = {path.stem for path in EXAMPLES_DIR.glob("*.txt")}
    assert committed - set(EXAMPLES) == set(), "example files with no generator"
    assert set(EXAMPLES) - committed == set(), "generators with no example file"


def test_multiply_example_matches_generator() -> None:
    """The committed multiply program is exactly what the generator produces."""
    from esolangs.tools.boolean import jaune_multiply

    path = BASE_DIR / "examples" / "multiply" / "jaune.txt"
    assert path.read_text(encoding="utf-8") == jaune_multiply()


# name -> (interpreter module, input lines, expected output, split lines)
CAT_EXAMPLES = {
    "between": ("register_based.between", ["hi"], "hi", True),
    "nevermind": ("register_based.nevermind", ["hi"], "hi\n", True),
    "6-5": ("tape_based.six_five", ["h"], "h", False),
    "modulous": ("stack_based.modulous", ["hi"], "hi", False),
    "suptiftam": ("other.suptiftam", ["hi"], "hi", False),
}

TRUTH_MACHINE_EXAMPLES = {
    "between": ("register_based.between", ["0"], "0", True),
    "brainif": ("tape_based.brainif", ["0"], "0", True),
    "circlefuck": ("tape_based.circlefuck", ["0"], "0", False),
    "factor": ("tape_based.factor", ["0"], "0", False),
    "forbin": ("other.forbin", ["0"], "0", False),
    "modulous": ("stack_based.modulous", ["0"], "0", False),
    "suptiftam": ("other.suptiftam", ["0"], "0", False),
}

BASE_DIR = Path(__file__).parent.parent


# name -> (interpreter module, input lines, expected output, split lines)
# The multiply examples feed two sentinel-delimited decimal operands: the
# digits of the first operand, a "*" line, the digits of the second, and a
# "#" line.  The program prints their product (see docs/walls.md).
MULTIPLY_EXAMPLES = {
    "jaune": ("tape_based.jaune", ["1", "2", "*", "3", "4", "#"], "408", False),
}

# name -> (interpreter module, input lines, expected output, split lines)
# The boolean examples demonstrate a language's boolean-function capability
# that is not an I/O truth machine (see docs/walls.md).  Minifuck's
# generator covers the 0-preserving two-input tables, so the committed AND2
# program reads two input bits (0/1 lines) and prints their AND.  ArrowQueue
# has no output and no runtime input: the committed program is the generated
# halt-vs-loop AND with one input zero (``_instantiate_arrowqueue(arrowqueue
# ("0001"), [0, 1])``), which halts (the `0` branch); the same table with
# both inputs one would loop forever instead (the `1` branch is not
# executed).  Point Break likewise has no output: the committed program is
# the wiki's own truth-machine, which halts for a 0 input and loops forever
# for any nonzero input (the `1` branch is not executed).  Eval likewise has
# no runtime input: the committed program is the generated AND2 template
# instantiated with one input zero (``instantiate(eval("0001"), [0, 1])``),
# which prints the result 0.  COD likewise has no runtime input: the
# committed program is the generated XOR template instantiated with both
# inputs one (``instantiate(cod("0110"), [1, 1])``), which prints 0 (see
# docs/cod_boolean_generator.md).
BOOLEAN_EXAMPLES = {
    "arrowqueue": ("grid_based.arrowqueue", [], "", True),
    "cod": ("grid_based.cod", [], "0\n", False),
    "eval": ("stack_based.eval", [], "0", False),
    "minifuck": ("tape_based.minifuck", ["0", "1"], "0", False),
    "point-break": ("register_based.point_break", ["0"], "", False),
    "wii2d": ("grid_based.wii2d", [], "1", True),
}


def run_with_input(name: str, subdir: str) -> None:
    if subdir == "multiply":
        examples = MULTIPLY_EXAMPLES
    elif subdir == "boolean":
        examples = BOOLEAN_EXAMPLES
    else:
        examples = CAT_EXAMPLES if subdir == "cat" else TRUTH_MACHINE_EXAMPLES
    module, inputs, expected, splitlines = examples[name]
    run = importlib.import_module("esolangs.interpreters." + module).run
    program = (
        (BASE_DIR / "examples" / subdir / f"{name}.txt")
        .read_text(encoding="utf-8")
        .rstrip("\n")
    )
    argument = program.splitlines() if splitlines else program

    buffer = io.StringIO()
    with patch("builtins.input", side_effect=inputs), redirect_stdout(buffer):
        run(argument, io=IO())
    assert buffer.getvalue() == expected


@pytest.mark.parametrize("name", sorted(CAT_EXAMPLES))
def test_cat_example(name: str) -> None:
    run_with_input(name, "cat")


@pytest.mark.parametrize("name", sorted(TRUTH_MACHINE_EXAMPLES))
def test_truth_machine_example(name: str) -> None:
    run_with_input(name, "truth-machine")


@pytest.mark.parametrize("name", sorted(BOOLEAN_EXAMPLES))
def test_boolean_example(name: str) -> None:
    run_with_input(name, "boolean")


@pytest.mark.parametrize("name", sorted(MULTIPLY_EXAMPLES))
def test_multiply_example(name: str) -> None:
    run_with_input(name, "multiply")
